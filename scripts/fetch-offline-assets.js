
import fs from 'fs';
import path from 'path';
import https from 'https';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ASSETS = [
    { name: 'TAILWIND_SCRIPT', url: 'https://cdn.tailwindcss.com' },
    { name: 'REACT_SCRIPT', url: 'https://unpkg.com/react@18/umd/react.production.min.js' },
    { name: 'REACT_DOM_SCRIPT', url: 'https://unpkg.com/react-dom@18/umd/react-dom.production.min.js' },
    { name: 'BABEL_SCRIPT', url: 'https://unpkg.com/@babel/standalone/babel.min.js' }
];

const OUTPUT_FILE = path.join(__dirname, '../services/offlineAssets.ts');

const fetchUrl = (url) => {
    return new Promise((resolve, reject) => {
        https.get(url, (res) => {
            // Handle Redirects
            if (res.statusCode === 301 || res.statusCode === 302) {
                if (res.headers.location) {
                    const newUrl = new URL(res.headers.location, url).toString();
                    console.log(`Redirecting to ${newUrl}...`);
                    fetchUrl(newUrl).then(resolve).catch(reject);
                    return;
                }
            }

            if (res.statusCode !== 200) {
                reject(new Error(`Failed to fetch ${url}: ${res.statusCode}`));
                return;
            }
            let data = '';
            res.on('data', (chunk) => data += chunk);
            res.on('end', () => resolve(data));
        }).on('error', reject);
    });
};

const main = async () => {
    console.log('Fetching offline assets...');
    try {
        const results = await Promise.all(ASSETS.map(async (asset) => {
            console.log(`Downloading ${asset.name}...`);
            const content = await fetchUrl(asset.url);
            // Escape backticks and standard JS string escapes if necessary
            // Since we are putting this in a template literal, only backticks and ${ need escaping
            const escapedContent = content
                .replace(/\\/g, '\\\\') // Escape backslashes first
                .replace(/`/g, '\\`')   // Escape backticks
                .replace(/\${/g, '\\${'); // Escape template interpolation start

            return `export const ${asset.name} = \`${escapedContent}\`;`;
        }));

        const fileContent = `// AUTO-GENERATED FILE - DO NOT EDIT\n// Generated by scripts/fetch-offline-assets.js\n\n${results.join('\n\n')}\n`;

        fs.writeFileSync(OUTPUT_FILE, fileContent);
        console.log(`Assets saved to ${OUTPUT_FILE}`);
    } catch (error) {
        console.error('Error fetching assets:', error);
        process.exit(1);
    }
};

main();
